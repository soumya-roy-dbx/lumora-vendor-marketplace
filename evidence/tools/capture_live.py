    app = api("get", f"/api/2.0/apps/{APP}", ok_fail=True)
    keep = {k: app.get(k) for k in ("name", "url", "app_status", "compute_status", "service_principal_client_id", "resources", "_error")}
    keep["active_deployment"] = {k: (app.get("active_deployment") or {}).get(k) for k in ("deployment_id", "status", "create_time", "source_code_path")}
    parts.append("## Databricks App\n\n```json\n" + json.dumps(keep, indent=2) + "\n```\n")
    did_file = os.path.join(ROOT, "dashboards", ".dashboard_id")
    if os.path.exists(did_file):
        did = open(did_file).read().strip()
        d = api("get", f"/api/2.0/lakeview/dashboards/{did}", ok_fail=True)
        pub = api("get", f"/api/2.0/lakeview/dashboards/{did}/published", ok_fail=True)
        spec = json.loads(d.get("serialized_dashboard", "{}") or "{}")
        parts.append("## AI/BI dashboard\n\n```json\n" + json.dumps({
            "dashboard_id": did, "display_name": d.get("display_name"), "lifecycle_state": d.get("lifecycle_state"),
            "pages": [pg.get("displayName") for pg in spec.get("pages", [])],
            "widgets": sum(len(pg.get("layout", [])) for pg in spec.get("pages", [])),
            "datasets": [ds.get("displayName") for ds in spec.get("datasets", [])],
            "ask_genie": spec.get("uiSettings", {}).get("genieSpace"),
            "published": pub}, indent=2) + "\n```\n")
    write("platform_status.md", "Platform status — Lakebase, Databricks App, AI/BI dashboard", parts)


