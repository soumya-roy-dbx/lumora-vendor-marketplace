def now():
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")


def api(method, path, body=None, ok_fail=False):
    cmd = ["databricks", "api", method, path, "-p", PROFILE] + (["--json", json.dumps(body)] if body is not None else [])
    out = subprocess.run(cmd, capture_output=True, text=True)
    if out.returncode != 0:
        if ok_fail:
            return {"_error": (out.stderr or out.stdout).strip()[:1500]}
        raise RuntimeError(out.stderr or out.stdout)
    return json.loads(out.stdout or "{}")


def whoami():
    return api("get", "/api/2.0/preview/scim/v2/Me").get("userName")


def sql(stmt):
    r = api("post", "/api/2.0/sql/statements", {"warehouse_id": WAREHOUSE, "statement": stmt, "wait_timeout": "50s"})
    st = r.get("status", {})
    while st.get("state") in ("PENDING", "RUNNING"):
        time.sleep(3)
        r = api("get", f"/api/2.0/sql/statements/{r['statement_id']}"); st = r.get("status", {})
    if st.get("state") != "SUCCEEDED":
        return None, None, st.get("error", {}).get("message", st.get("state"))
    cols = [c["name"] for c in r["manifest"]["schema"]["columns"]]
    return cols, (r.get("result") or {}).get("data_array") or [], None


def md_rows(cols, rows, limit=40):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in rows[:limit]:
        out.append("| " + " | ".join("NULL" if v is None else str(v).replace("|", "\\|")[:100] for v in row) + " |")
    if len(rows) > limit:
        out.append(f"\n_… {len(rows) - limit} more rows_")
    return "\n".join(out)


def block(title, stmt):
    cols, rows, err = sql(stmt)
    body = f"```text\nERROR: {err}\n```" if err else md_rows(cols, rows) + f"\n\n_{len(rows)} row(s)_"
    return f"### {title}\n\n```sql\n{stmt.strip()}\n```\n\n{body}\n"


def write(name, header, parts):
    tag = os.environ.get("EVIDENCE_TAG")          # e.g. "finance" -> sql_evidence_finance.md
    if tag:
        name, header = name.replace(".md", f"_{tag}.md"), f"{header} [{tag} view]"
    path = os.path.join(OUT, name)
    open(path, "w").write(f"# {header}\n\n_Captured {now()} as `{whoami()}` (profile {PROFILE}). "
                          f"Generated by `evidence/tools/capture_live.py` — output is verbatim from the live workspace._\n\n"
                          + "\n".join(parts))
    print("wrote", path)


